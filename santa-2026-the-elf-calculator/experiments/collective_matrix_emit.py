"""Turn noisy product-table hypotheses into fully paid, register-checked programs.

The hypotheses are generated by the public matrix detector from the puzzle alone.
Both the arithmetic-plan assembly and the scalar ingredient solver run locally.
"""

import argparse
import csv
import json
import random
from collections import defaultdict
from pathlib import Path

from depth_graph_study import shallow
from first_solver import validate
from hybrid_graph_search import (
    Construction,
    compile_changes,
    live_rollout,
    program_rules,
    rooted_rules,
)

ROOT = Path(__file__).resolve().parents[1]


def terminal(t, p, k, d, e, limit):
    """Generate k*(p+d)+e with both signed edits and every intermediate checked."""
    rules = []

    def add(a, b):
        if b:
            rules.append(("+" if b > 0 else "-", a, abs(b), a + b))
        return a + b

    inner = add(p, d)
    product = k * inner
    if k != 1:
        rules.append(("*", inner, k, product))
    value = add(product, e)
    if value == t and all(
        1 <= r[3] <= limit and 1 <= r[1] <= limit and 1 <= r[2] <= limit for r in rules
    ):
        return tuple(rules)


def make_options(p, fits):
    targets = sorted(json.loads(p["targets"]))
    limit = int(p["value_limit"])
    hubs = fits["hubs"]
    choices = defaultdict(set)
    atom_targets = set(hubs)

    def add(t, head, body):
        if body is not None:
            path = head + body
            if path and path[-1][3] == t and all(t not in r[1:3] for r in path):
                choices[t].add(path)

    for cell in fits["targets"]:
        t, a, b, k, d, e, r = (cell[n] for n in ("t", "a", "b", "k", "d", "e", "r"))
        assert t == k * a * b + r and r == k * d + e
        atom_targets.update(n for n in (k, abs(d), abs(e), abs(r)) if n)
        pair = (("*", a, b, a * b),)
        for d0 in {0, d, r // k, -((-r) // k)}:
            add(t, pair, terminal(t, a * b, k, d0, r - k * d0, limit))
    # Other observed outputs can replace the uncorrected product, even for a
    # different coefficient, e.g. k*(P+c)+e instead of synthesizing P twice.
    for t in targets:
        for base in targets:
            if base >= t:
                break
            k = (t + base // 2) // base
            if not (1 <= k <= 3_000_000):
                continue
            r = t - k * base
            for d in {0, r // k, -((-r) // k)}:
                e = r - k * d
                if abs(d) <= 8192 and abs(e) <= 8192:
                    add(t, (), terminal(t, base, k, d, e, limit))
    return choices, atom_targets


def solve(p, fits, restarts, seed):
    options, required = make_options(p, fits)
    starts = set(json.loads(p["starting_values"]))
    goals = sorted(json.loads(p["targets"]))
    unmatched = {t for t in goals if t not in {r["t"] for r in fits["targets"]}}
    proxy_goals = sorted((required | unmatched) - starts)
    proxy = dict(p, targets=json.dumps(proxy_goals))
    model = Construction(proxy)
    rng = random.Random(seed)
    initial, _ = live_rollout(model, seed=seed, virtual=True, policy="order")
    if initial is None:
        initial = model.construct()
    shallow_book, _ = shallow(starts, int(p["value_limit"]), 2)
    atoms = {v: r for v, r in shallow_book.items() if r is not None}
    for rule in program_rules(proxy, initial):
        if rule[3] not in starts and rule[3] not in rule[1:3]:
            atoms.setdefault(rule[3], rule)
    # A shallow recipe may refer back to an operand that another recipe replaces.
    # Give the independently scheduled proxy precedence to retain acyclicity.
    for rule in reversed(program_rules(proxy, initial)):
        if rule[3] not in starts and rule[3] not in rule[1:3]:
            atoms[rule[3]] = rule

    def supply(v):
        if v in starts or v in atoms:
            return
        if v == 1:
            a = min(starts)
            atoms[v] = ("/", a, a, 1)
        elif v % 2:
            atoms[v] = ("+", v - 1, 1, v)
        else:
            atoms[v] = ("+", v // 2, v // 2, v)
        for a in atoms[v][1:3]:
            supply(a)

    for t in goals:
        supply(t)
        for path in options[t]:
            for rule in path:
                for x in rule[1:3]:
                    supply(x)

    def build(selected, order, emit=False):
        graph = atoms.copy()
        # First derivation wins for a shared interior value; terminal choices
        # override generic scalar recipes. Inputs in a path are never free.
        interior = {}
        for t in order:
            path = selected[t]
            if path:
                for r in path:
                    if r[3] not in starts:
                        interior.setdefault(r[3], r)
        graph.update(interior)
        for t, path in selected.items():
            if path:
                graph[t] = path[-1]
        try:
            seq = rooted_rules(starts, order, graph)
        except ValueError:
            return None if emit else 10**6
        if emit:
            return compile_changes(p, seq, goals)
        return len(seq)

    paths = {t: sorted(options[t]) for t in goals}
    best = None
    history = []
    for rep in range(restarts):
        order = goals.copy()
        if rep:
            rng.shuffle(order)
        selected = {
            t: rng.choice(paths[t])
            if paths[t] and rep
            else (min(paths[t], key=len) if paths[t] else ())
            for t in goals
        }
        prior = build(selected, order)
        for _ in range(3):
            old = prior
            for t in order:
                was = selected[t]
                candidates = paths[t].copy()
                if t in unmatched:
                    candidates.append(())
                rng.shuffle(candidates)
                for path in candidates:
                    selected[t] = path
                    n = build(selected, order)
                    if n < prior:
                        was, prior = path, n
                selected[t] = was
            if prior == old:
                break
        if best is None or prior < len(best):
            trial = build(selected, order, True)
            if trial is not None and (not best or len(trial) < len(best)):
                validate(p, trial)
                best = trial
        history.append(len(best) if best is not None else None)
    return dict(
        program=best,
        steps=len(best) if best else None,
        curve=history,
        hubs=fits["hubs"],
        fits=len(fits["targets"]),
        total_targets=len(goals),
        choices=sum(map(len, paths.values())),
        proxy_steps=len(initial),
    )


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--trials", type=int, default=12)
    ap.add_argument("--seed", type=int, default=20261127)
    args = ap.parse_args()
    cases = json.loads((ROOT / "reports/collective_matrix_fits.json").read_text())[
        "cases"
    ]
    with (ROOT / "data/puzzles.csv").open() as stream:
        puzzles = {r["id"]: r for r in csv.DictReader(stream)}
    out = {}
    for i, fit in cases.items():
        if not fit["targets"]:
            continue
        out[i] = solve(puzzles[i], fit, args.trials, args.seed)
        print(i, out[i]["fits"], out[i]["steps"], flush=True)
    (ROOT / "reports/collective_matrix_emit.json").write_text(
        json.dumps(
            dict(seed=args.seed, trials=args.trials, cases=out), separators=(",", ":")
        )
        + "\n"
    )


if __name__ == "__main__":
    main()
